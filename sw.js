self.addEventListener('install', e => {
  self.skipWaiting();
  // 逐檔下載，個別失敗不擋安裝（之後開到那頁時 network-first 會補存）。
  e.waitUntil(caches.open(CACHE).then(c => Promise.allSettled(
    PRECACHE.map(f => fetch(new Request(f, { cache: 'reload' })).then(r => r.ok && c.put(f, r)))
  )));
});
self.addEventListener('activate', e => e.waitUntil(
  caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('zr-toolbox') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim())
));
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(fetch(req).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  }).catch(async () => (await caches.match(req, { ignoreSearch: true }))
    || (req.mode === 'navigate' && await caches.match('index.html')) || Response.error()));
});
